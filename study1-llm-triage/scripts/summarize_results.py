#!/usr/bin/env python3
"""Regenerate results/README.md (summary tables) from the result CSVs. Missing results are skipped."""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "results"


def read(path):
    p = R / path
    return list(csv.DictReader(open(p))) if p.exists() else None


def f3(x):
    return f"{float(x):.3f}" if x not in ("", None) else ""


def tool_rows(name, path):
    rows = read(path)
    if not rows:
        return None
    by = {r["category"]: r for r in rows}
    pooled = by["OVERALL (pooled)"]
    avg = by["OVERALL (avg of categories, Benchmark style)"]
    cats = {c: r["score_TPR_minus_FPR"] for c, r in by.items() if not c.startswith("OVERALL")}
    return name, pooled, avg, cats


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main():
    md = ["# Results summary", "",
          "Generated by `scripts/summarize_results.py` from the CSVs in this folder; do not edit by hand.",
          "Score = TPR - FPR (OWASP Benchmark score). 'Benchmark avg' averages the score over categories;",
          "'pooled' computes it over all test cases at once.",
          "Guardrails v2 is frozen at git tag `guardrails-v2-frozen` (commit d2a28b6) before the held-out runs",
          "(real-world CVE set, Juliet); see FINAL_COMPARISON.md for all datasets.", ""]

    # SAST tools on BenchmarkJava
    tools = [t for t in (
        tool_rows("Semgrep (p/java + p/owasp-top-ten)", "pilot/semgrep_score.csv"),
        tool_rows("SonarQube Community Build 26.10", "sonarqube/sonarqube_score.csv"),
        tool_rows("SpotBugs + FindSecBugs", "spotbugs/spotbugs_score.csv"),
        tool_rows("CodeQL (java-security-extended)", "codeql/codeql_score.csv"),
    ) if t]
    md += ["## SAST tools on OWASP Benchmark Java 1.2 (2,740 tests)", ""]
    md.append(table(["Tool", "TP", "FP", "FN", "TN", "Precision", "TPR", "FPR", "Score (pooled)", "Score (Benchmark avg)"],
                    [[n, p["TP"], p["FP"], p["FN"], p["TN"], f3(p["precision"]), f3(p["recall_TPR"]), f3(p["FPR"]),
                      f3(p["score_TPR_minus_FPR"]), f3(a["score_TPR_minus_FPR"])] for n, p, a, _ in tools]))
    cats = sorted({c for *_, cs in tools for c in cs})
    md += ["", "Per-category score:", ""]
    md.append(table(["Category"] + [n.split(" (")[0] for n, *_ in tools],
                    [[c] + [f3(cs.get(c, "")) for *_, cs in tools] for c in cats]))

    comb = read("combined/java_all_tools.csv") or read("combined/java_semgrep_sonarqube.csv")
    if comb:
        variants = list(dict.fromkeys(r["variant"] for r in comb))
        get = {(r["variant"], r["category"]): r for r in comb}
        md += ["", "### Combining tools (a test counts as flagged if the tools in the variant flag it)", "",
               "*union* = any of the tools, *intersection* = all of them, *A+B* = union of a pair.", ""]
        md.append(table(["Variant", "TPR", "FPR", "Score (pooled)", "Score (Benchmark avg)"],
                        [[v, f3(get[(v, "OVERALL (pooled)")]["TPR"]), f3(get[(v, "OVERALL (pooled)")]["FPR"]),
                          f3(get[(v, "OVERALL (pooled)")]["score"]), f3(get[(v, "OVERALL (avg of categories)")]["score"])]
                         for v in variants]))

    # Triage
    md += ["", "## Triage of Semgrep findings on BenchmarkJava (1,763 findings, 1,482 flagged tests)", "",
           "Policies: *baseline* = Semgrep alone; *unguarded* = dismiss whenever the model says false positive;",
           "*guarded-v1* = schema check, cited-lines check, confidence >= 0.8, unsure keeps, error-level rules never",
           "auto-dismissed; *guarded* (v2) = v1 without the confidence gate, plus weak-crypto/hash/random findings",
           "never dismissed; *guarded-no-X* = v2 with one guardrail off.", ""]
    runs = [("Qwen2.5-Coder 7B (LLM)", "triage/qwen2.5-coder_7b/scores.csv"),
            ("Qwen2.5-Coder 14B (LLM)", "triage/qwen2.5-coder_14b/scores.csv"),
            ("Random Forest, grouped 5-fold CV", "triage/ml_rf/scores.csv"),
            ("Random Forest, leave-one-category-out", "triage/ml_rf_loco/scores.csv")]
    rows = []
    for name, path in runs:
        for r in read(path) or []:
            if r["policy"] == "baseline" and rows:
                continue
            rows.append([name if r["policy"] != "baseline" else "Semgrep alone", r["policy"],
                         r["dismissed_on_fake_vuln_tests"], r["dismissed_on_real_vuln_tests"],
                         r["TP"], r["FP"], f3(r["precision"]), f3(r["TPR"]), f3(r["FPR"]),
                         f3(r["score_pooled"]), f3(r["score_benchmark_avg"])])
    md.append(table(["Triage", "Policy", "Dismissed (fake vuln)", "Dismissed (real vuln)", "TP", "FP",
                     "Precision", "TPR", "FPR", "Score (pooled)", "Score (Benchmark avg)"], rows))

    cq = read("triage_codeql/qwen2.5-coder_7b/scores.csv")
    if cq:
        md += ["", "## Triage of CodeQL findings on BenchmarkJava (Qwen2.5-Coder 7B)", ""]
        md.append(table(["Policy", "Dismissed (fake vuln)", "Dismissed (real vuln)", "TP", "FP", "Precision", "TPR",
                         "FPR", "Score (pooled)", "Score (Benchmark avg)"],
                        [["CodeQL alone" if r["policy"] == "baseline" else r["policy"], r["dismissed_on_fake_vuln_tests"],
                          r["dismissed_on_real_vuln_tests"], r["TP"], r["FP"], f3(r["precision"]), f3(r["TPR"]),
                          f3(r["FPR"]), f3(r["score_pooled"]), f3(r["score_benchmark_avg"])] for r in cq]))

    md += ["", "## Notes", "",
           "- Random Forest numbers are optimistic: Benchmark test cases are generated from shared templates,",
           "  which a classifier can learn (95% accuracy even on held-out categories). They bound what pattern",
           "  learning achieves on synthetic data, not real-world triage quality.",
           "- SonarQube Community Build has no taint analysis, hence 0 on injection categories.",
           "- Timing: the 7B runs ran before the 150 W GPU cap; see the repo README.", ""]
    (R / "README.md").write_text("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
